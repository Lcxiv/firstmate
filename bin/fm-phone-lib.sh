#!/usr/bin/env bash
# Shared Discord phone-mode configuration, private-artifact, and transport
# helpers for fm-phone-poll.sh, fm-phone-reply.sh, and locked bootstrap setup.
#
# Phone mode is deliberately Discord-only and inert unless all three required
# values resolve non-empty and valid:
#   FM_PHONE_DISCORD_TOKEN  Discord bot token (secret)
#   FM_PHONE_CAPTAIN_ID     Discord user id allowed to command this home
#   FM_PHONE_CHANNEL_ID     private Discord channel id allowed to command it
#
# Direct clients accept environment overrides and otherwise read FM_HOME/.env;
# FM_PHONE_ENV_FILE redirects that read for tests and direct invocations only.
# Bootstrap intentionally inspects FM_HOME/.env itself before generating state.
# The generated watcher shim exports FM_PHONE_CONFIG_SOURCE=home-env, which
# pins resolution to that same file so an inherited process environment can
# never authenticate a different captain, channel, or configuration source than
# the one that gated activation.
#
# This file is sourced, never executed. It reuses fm-x-lib.sh's hardened private
# artifact publisher and .env reader; sourcing that library activates no X-mode
# behavior.

SCRIPT_DIR_PHONE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=bin/fm-x-lib.sh
. "$SCRIPT_DIR_PHONE/fm-x-lib.sh"

FM_PHONE_DISCORD_API=https://discord.com/api/v10
FM_PHONE_UA='firstmate-phone/1.0 (+https://github.com/Lcxiv/firstmate)'

fm_phone_config_get() {
  local key=$1 env_file
  if [ "${FM_PHONE_CONFIG_SOURCE:-}" = home-env ]; then
    fmx_env_get "$key" "$FM_HOME/.env"
    return $?
  fi
  env_file="${FM_PHONE_ENV_FILE:-$FM_HOME/.env}"
  if [ -n "${!key+x}" ]; then
    printf '%s' "${!key-}"
    return 0
  fi
  fmx_env_get "$key" "$env_file"
}

fm_phone_bounded() {
  local raw=$1 fallback=$2 lo=$3 hi=$4
  case "$raw" in
    ''|*[!0-9]*) raw=$fallback ;;
  esac
  [ "${#raw}" -le 9 ] || raw=$fallback
  [ "$raw" -ge "$lo" ] || raw=$lo
  [ "$raw" -le "$hi" ] || raw=$hi
  printf '%s' "$raw"
}

fm_phone_truthy() {
  case "$1" in
    ''|0|false|FALSE|no|NO|off|OFF) return 1 ;;
    *) return 0 ;;
  esac
}

fm_phone_discord_id_valid() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
    *) return 0 ;;
  esac
}

# Resolve the direct-client configuration into FM_PHONE_TOKEN,
# FM_PHONE_CAPTAIN, FM_PHONE_CHANNEL, FM_PHONE_TIMEOUT, FM_PHONE_ACK_ENABLED,
# and FM_PHONE_CONFIGURED.
# shellcheck disable=SC2034 # Resolved globals are read by scripts after sourcing.
fm_phone_load_config() {
  local ack timeout
  FM_PHONE_TOKEN=$(fm_phone_config_get FM_PHONE_DISCORD_TOKEN)
  FM_PHONE_CAPTAIN=$(fm_phone_config_get FM_PHONE_CAPTAIN_ID)
  FM_PHONE_CHANNEL=$(fm_phone_config_get FM_PHONE_CHANNEL_ID)
  timeout=$(fm_phone_config_get FM_PHONE_TIMEOUT_SECS)
  ack=$(fm_phone_config_get FM_PHONE_ACK)

  FM_PHONE_CONFIGURED=0
  if [ -n "$FM_PHONE_TOKEN" ] \
    && fm_phone_discord_id_valid "$FM_PHONE_CAPTAIN" \
    && fm_phone_discord_id_valid "$FM_PHONE_CHANNEL"; then
    case "$FM_PHONE_TOKEN" in
      *$'\n'*|*$'\r'*) ;;
      *) FM_PHONE_CONFIGURED=1 ;;
    esac
  fi

  FM_PHONE_TIMEOUT=$(fm_phone_bounded "$timeout" 5 1 10)
  # shellcheck disable=SC2034 # Read by fm-phone-poll.sh after sourcing.
  FM_PHONE_ACK_ENABLED=1
  fm_phone_truthy "${ack:-1}" || FM_PHONE_ACK_ENABLED=0
}

fm_phone_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Discord phone command poll shim.' \
    '# Its registered content identity dispatches the trusted repository poll.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    'export FM_PHONE_CONFIG_SOURCE=home-env' \
    "exec $(printf '%q' "$root/bin/fm-phone-poll.sh")"
}

fm_phone_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_single_link_file_mode_valid "$file" 700 || return 1
  cmp -s "$file" <(fm_phone_poll_shim_content "$home" "$root")
}

fm_phone_auth_header_file() {
  local file
  [ "${FM_PHONE_CONFIGURED:-0}" = 1 ] || return 1
  case "$FM_PHONE_TOKEN" in
    ''|*$'\n'*|*$'\r'*) return 1 ;;
  esac
  file=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-phone-auth.XXXXXX") || return 1
  chmod 600 "$file" 2>/dev/null || { rm -f "$file"; return 1; }
  printf 'Authorization: Bot %s\n' "$FM_PHONE_TOKEN" > "$file" \
    || { rm -f "$file"; return 1; }
  printf '%s\n' "$file"
}

# Stage the configured private channel URL in a mode-0600 curl config rather
# than argv. MODE is "poll" or "post"; CURSOR is optional for poll.
fm_phone_url_config_file() {
  local mode=$1 cursor=${2:-} url file
  [ "${FM_PHONE_CONFIGURED:-0}" = 1 ] || return 1
  case "$mode" in
    poll)
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages?limit=50"
      if [ -n "$cursor" ] && [ "$cursor" != 0 ]; then
        fm_phone_discord_id_valid "$cursor" || return 1
        url="$url&after=$cursor"
      fi
      ;;
    post)
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages"
      ;;
    *) return 1 ;;
  esac
  file=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-phone-url.XXXXXX") || return 1
  chmod 600 "$file" 2>/dev/null || { rm -f "$file"; return 1; }
  printf 'url = "%s"\n' "$url" > "$file" || { rm -f "$file"; return 1; }
  printf '%s\n' "$file"
}

# One bounded Discord history GET. Writes the response JSON to BODY and prints
# only the HTTP code. Token and channel id remain in private temporary files.
fm_phone_poll_request() (
  local body=$1 cursor=${2:-0} auth_file='' url_file='' code
  trap 'rm -f "$auth_file" "$url_file"' EXIT HUP INT TERM
  auth_file=$(fm_phone_auth_header_file) || return 1
  url_file=$(fm_phone_url_config_file poll "$cursor") || return 1
  code=$(curl -s -m "$FM_PHONE_TIMEOUT" --connect-timeout "$FM_PHONE_TIMEOUT" \
    -o "$body" -w '%{http_code}' \
    -H "@$auth_file" \
    -H 'Accept: application/json' \
    -H "User-Agent: $FM_PHONE_UA" \
    --config "$url_file" 2>/dev/null) || return 1
  printf '%s' "$code"
)

# One bounded Discord message POST using a payload file. It is intentionally
# silent; callers translate failure without ever printing config or response
# bodies that could carry private channel detail.
fm_phone_post_payload() (
  local payload=$1 auth_file='' url_file='' body_file='' code
  trap 'rm -f "$auth_file" "$url_file" "$body_file"' EXIT HUP INT TERM
  auth_file=$(fm_phone_auth_header_file) || return 1
  url_file=$(fm_phone_url_config_file post) || return 1
  body_file=$(mktemp "${TMPDIR:-/tmp}/fm-phone-post-body.XXXXXX") || return 1
  code=$(curl -s -m "$FM_PHONE_TIMEOUT" --connect-timeout "$FM_PHONE_TIMEOUT" \
    -o "$body_file" -w '%{http_code}' \
    -X POST \
    -H "@$auth_file" \
    -H 'Content-Type: application/json' \
    -H "User-Agent: $FM_PHONE_UA" \
    --data-binary "@$payload" \
    --config "$url_file" 2>/dev/null) || return 1
  case "$code" in
    2[0-9][0-9]) return 0 ;;
    *) return 1 ;;
  esac
)

# Build a Discord message payload. REPLY_ID may be empty; when present it is a
# safe numeric snowflake and only the first chunk should carry the reference.
fm_phone_message_payload() {
  local text=$1 reply_id=${2:-}
  [ -z "$reply_id" ] || fm_phone_discord_id_valid "$reply_id" || return 1
  jq -cn \
    --arg text "$text" \
    --arg reply "$reply_id" \
    --arg channel "$FM_PHONE_CHANNEL" '
      {content:$text, allowed_mentions:{parse:[], replied_user:false}}
      + (if $reply == "" then {}
         else {message_reference:{message_id:$reply, channel_id:$channel, fail_if_not_exists:false}}
         end)
    '
}

fm_phone_cursor_get() {
  local state=$1 file="$1/phone-cursor" value
  if [ ! -e "$file" ] && [ ! -L "$file" ]; then
    printf '0\n'
    return 0
  fi
  fmx_private_artifact_file_valid "$state" phone-cursor 600 || return 1
  exec 8< "$file" || return 1
  IFS= read -r value <&8 || { exec 8<&-; return 1; }
  if IFS= read -r _extra <&8; then
    exec 8<&-
    return 1
  fi
  exec 8<&-
  fm_phone_discord_id_valid "$value" || return 1
  printf '%s\n' "$value"
}

fm_phone_cursor_set() {
  local state=$1 cursor=$2
  fm_phone_discord_id_valid "$cursor" || return 1
  printf '%s\n' "$cursor" \
    | fmx_private_artifact_publish_stdin "$state" phone-cursor 600
}

# Print a Discord snowflake for the current local time using Discord's public
# 2015-01-01 epoch and 22-bit shift. It is used only to baseline a missing
# cursor at "now", never to identify a real message. Fails when the clock or
# the shell's integer width cannot produce a plausible snowflake.
fm_phone_now_snowflake() {
  local secs value
  secs=$(date +%s 2>/dev/null) || return 1
  case "$secs" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "$secs" -gt 1420070400 ] || return 1
  value=$(( (secs * 1000 - 1420070400000) * 4194304 )) || return 1
  fm_phone_discord_id_valid "$value" || return 1
  [ "${#value}" -ge 17 ] && [ "${#value}" -le 19 ] || return 1
  printf '%s' "$value"
}

# Return 0 when A is strictly newer than B, comparing arbitrary-length decimal
# Discord snowflakes without numeric conversion or floating-point precision.
fm_phone_id_newer() {
  local a=$1 b=$2
  fm_phone_discord_id_valid "$a" || return 1
  fm_phone_discord_id_valid "$b" || return 1
  [ "${#a}" -gt "${#b}" ] && return 0
  [ "${#a}" -lt "${#b}" ] && return 1
  [[ "$a" > "$b" ]]
}

# Atomically stash one normalized Discord message object. Return 0 for a newly
# published inbox entry, 1 when the same valid id already exists, and 2 on an
# unsafe path or write failure.
fm_phone_inbox_stash() (
  local state=$1 message_id=$2 json_file=$3
  fm_phone_discord_id_valid "$message_id" || return 2
  set -o pipefail
  jq -c '.' "$json_file" 2>/dev/null \
    | fmx_private_artifact_publish_stdin_once "$state/phone-inbox" "$message_id.json" 600
)
