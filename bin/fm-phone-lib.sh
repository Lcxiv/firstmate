#!/usr/bin/env bash
# Shared Discord phone-mode configuration, private-artifact, and transport
# helpers for fm-phone-poll.sh, fm-phone-reply.sh, and locked bootstrap setup.
#
# Phone mode is deliberately Discord-only and inert unless all three required
# values resolve non-empty and valid:
#   FM_PHONE_DISCORD_TOKEN  Discord bot token (secret)
#   FM_PHONE_CAPTAIN_ID     Discord user id allowed to command this home
#   FM_PHONE_CHANNEL_ID     private Discord channel id allowed to command it
#
# Direct clients accept environment overrides and otherwise read FM_HOME/.env;
# FM_PHONE_ENV_FILE redirects that read for tests and direct invocations only.
# Bootstrap intentionally inspects FM_HOME/.env itself before generating state.
# The generated watcher shim exports FM_PHONE_CONFIG_SOURCE=home-env, which
# pins resolution to that same file so an inherited process environment can
# never authenticate a different captain, channel, or configuration source than
# the one that gated activation.
#
# This file is sourced, never executed. It reuses fm-x-lib.sh's hardened private
# artifact publisher and .env reader; sourcing that library activates no X-mode
# behavior.

SCRIPT_DIR_PHONE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=bin/fm-x-lib.sh
. "$SCRIPT_DIR_PHONE/fm-x-lib.sh"

FM_PHONE_DISCORD_API=https://discord.com/api/v10
FM_PHONE_UA='firstmate-phone/1.0 (+https://github.com/Lcxiv/firstmate)'

# The receipt reaction, percent-encoded for Discord's reaction route. This is
# UTF-8 for the anchor the captain sees on their own message.
FM_PHONE_ACK_EMOJI_ENCODED='%E2%9A%93'

# The live summary's leading marker. It is ordinary captain-facing text, and it
# is also what lets a home that lost its durable record recognise its own
# summary in channel history instead of posting a second one.
# shellcheck disable=SC2034 # Read by fm-phone-summary.sh after sourcing.
FM_PHONE_SUMMARY_MARKER='⚓'

fm_phone_config_get() {
  local key=$1 env_file
  if [ "${FM_PHONE_CONFIG_SOURCE:-}" = home-env ]; then
    fmx_env_get "$key" "$FM_HOME/.env"
    return $?
  fi
  env_file="${FM_PHONE_ENV_FILE:-$FM_HOME/.env}"
  if [ -n "${!key+x}" ]; then
    printf '%s' "${!key-}"
    return 0
  fi
  fmx_env_get "$key" "$env_file"
}

fm_phone_bounded() {
  local raw=$1 fallback=$2 lo=$3 hi=$4
  case "$raw" in
    ''|*[!0-9]*) raw=$fallback ;;
  esac
  [ "${#raw}" -le 9 ] || raw=$fallback
  [ "$raw" -ge "$lo" ] || raw=$lo
  [ "$raw" -le "$hi" ] || raw=$hi
  printf '%s' "$raw"
}

fm_phone_truthy() {
  case "$1" in
    ''|0|false|FALSE|no|NO|off|OFF) return 1 ;;
    *) return 0 ;;
  esac
}

fm_phone_discord_id_valid() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
    *) return 0 ;;
  esac
}

# Resolve the direct-client configuration into FM_PHONE_TOKEN,
# FM_PHONE_CAPTAIN, FM_PHONE_CHANNEL, FM_PHONE_TIMEOUT, FM_PHONE_ACK_ENABLED,
# and FM_PHONE_CONFIGURED.
# shellcheck disable=SC2034 # Resolved globals are read by scripts after sourcing.
fm_phone_load_config() {
  local ack timeout
  FM_PHONE_TOKEN=$(fm_phone_config_get FM_PHONE_DISCORD_TOKEN)
  FM_PHONE_CAPTAIN=$(fm_phone_config_get FM_PHONE_CAPTAIN_ID)
  FM_PHONE_CHANNEL=$(fm_phone_config_get FM_PHONE_CHANNEL_ID)
  timeout=$(fm_phone_config_get FM_PHONE_TIMEOUT_SECS)
  ack=$(fm_phone_config_get FM_PHONE_ACK)

  FM_PHONE_CONFIGURED=0
  if [ -n "$FM_PHONE_TOKEN" ] \
    && fm_phone_discord_id_valid "$FM_PHONE_CAPTAIN" \
    && fm_phone_discord_id_valid "$FM_PHONE_CHANNEL"; then
    case "$FM_PHONE_TOKEN" in
      *$'\n'*|*$'\r'*) ;;
      *) FM_PHONE_CONFIGURED=1 ;;
    esac
  fi

  FM_PHONE_TIMEOUT=$(fm_phone_bounded "$timeout" 5 1 10)
  # shellcheck disable=SC2034 # Read by fm-phone-poll.sh after sourcing.
  FM_PHONE_ACK_ENABLED=1
  fm_phone_truthy "${ack:-1}" || FM_PHONE_ACK_ENABLED=0
}

fm_phone_poll_shim_content() {
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - Discord phone command poll shim.' \
    '# Its registered content identity dispatches the trusted repository poll.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    'export FM_PHONE_CONFIG_SOURCE=home-env' \
    "exec $(printf '%q' "$root/bin/fm-phone-poll.sh")"
}

fm_phone_poll_shim_valid() {
  local file=$1 home=$2 root=$3
  fmx_single_link_file_mode_valid "$file" 700 || return 1
  cmp -s "$file" <(fm_phone_poll_shim_content "$home" "$root")
}

fm_phone_auth_header_file() {
  local file
  [ "${FM_PHONE_CONFIGURED:-0}" = 1 ] || return 1
  case "$FM_PHONE_TOKEN" in
    ''|*$'\n'*|*$'\r'*) return 1 ;;
  esac
  file=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-phone-auth.XXXXXX") || return 1
  chmod 600 "$file" 2>/dev/null || { rm -f "$file"; return 1; }
  printf 'Authorization: Bot %s\n' "$FM_PHONE_TOKEN" > "$file" \
    || { rm -f "$file"; return 1; }
  printf '%s\n' "$file"
}

# Stage the configured private channel URL in a mode-0600 curl config rather
# than argv. MODE selects the route; ARG is the cursor for "poll", a message id
# for the message-scoped routes, and unused otherwise. Every route is built from
# the configured channel id and a validated numeric id, so no caller-supplied
# text ever reaches the URL.
fm_phone_url_config_file() {
  local mode=$1 arg=${2:-} url file limit
  [ "${FM_PHONE_CONFIGURED:-0}" = 1 ] || return 1
  case "$mode" in
    poll)
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages?limit=50"
      if [ -n "$arg" ] && [ "$arg" != 0 ]; then
        fm_phone_discord_id_valid "$arg" || return 1
        url="$url&after=$arg"
      fi
      ;;
    post)
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages"
      ;;
    recent)
      # A bounded page of recent history, used to re-find this home's own live
      # summary. It needs only the read access the poll route already uses.
      limit=$(fm_phone_bounded "$arg" 50 1 100)
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages?limit=$limit"
      ;;
    message)
      fm_phone_discord_id_valid "$arg" || return 1
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages/$arg"
      ;;
    react)
      fm_phone_discord_id_valid "$arg" || return 1
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/messages/$arg/reactions/$FM_PHONE_ACK_EMOJI_ENCODED/@me"
      ;;
    pin)
      fm_phone_discord_id_valid "$arg" || return 1
      url="$FM_PHONE_DISCORD_API/channels/$FM_PHONE_CHANNEL/pins/$arg"
      ;;
    *) return 1 ;;
  esac
  file=$(umask 077; mktemp "${TMPDIR:-/tmp}/fm-phone-url.XXXXXX") || return 1
  chmod 600 "$file" 2>/dev/null || { rm -f "$file"; return 1; }
  printf 'url = "%s"\n' "$url" > "$file" || { rm -f "$file"; return 1; }
  printf '%s\n' "$file"
}

# One bounded Discord request. Writes the response body to BODY and prints only
# the HTTP code; returns 1 when the request could not be made at all. Token and
# channel id stay in private temporary files, never in argv. This is the single
# transport for every route below, so the timeout, the header set, and the
# secret handling cannot drift between verbs.
fm_phone_api_request() (
  local method=$1 mode=$2 arg=$3 body=$4 payload=${5:-}
  local auth_file='' url_file='' code
  trap 'rm -f "$auth_file" "$url_file"' EXIT HUP INT TERM
  auth_file=$(fm_phone_auth_header_file) || return 1
  url_file=$(fm_phone_url_config_file "$mode" "$arg") || return 1
  set -- -s -m "$FM_PHONE_TIMEOUT" --connect-timeout "$FM_PHONE_TIMEOUT" \
    -o "$body" -w '%{http_code}' \
    -X "$method" \
    -H "@$auth_file" \
    -H 'Accept: application/json' \
    -H "User-Agent: $FM_PHONE_UA"
  if [ -n "$payload" ]; then
    set -- "$@" -H 'Content-Type: application/json' --data-binary "@$payload"
  fi
  code=$(curl "$@" --config "$url_file" 2>/dev/null) || return 1
  printf '%s' "$code"
)

# One bounded Discord history GET. Writes the response JSON to BODY and prints
# only the HTTP code.
fm_phone_poll_request() {
  fm_phone_api_request GET poll "${2:-0}" "$1"
}

# One bounded page of recent channel history into BODY. Prints the HTTP code.
fm_phone_recent_request() {
  fm_phone_api_request GET recent "${2:-50}" "$1"
}

# One bounded Discord message POST using a payload file. When BODY_OUT is given
# the created message object is written there so a caller can keep its id. It is
# intentionally silent; callers translate failure without ever printing config
# or response bodies that could carry private channel detail.
fm_phone_post_payload() (
  local payload=$1 body_out=${2:-} scratch='' body code rc
  trap 'rm -f "$scratch"' EXIT HUP INT TERM
  body=$body_out
  if [ -z "$body" ]; then
    scratch=$(mktemp "${TMPDIR:-/tmp}/fm-phone-post-body.XXXXXX") || return 1
    body=$scratch
  fi
  code=$(fm_phone_api_request POST post '' "$body" "$payload")
  rc=$?
  [ "$rc" = 0 ] || return 1
  case "$code" in
    2[0-9][0-9]) return 0 ;;
    *) return 1 ;;
  esac
)

# Add this home's receipt reaction to one captain message. Returns 0 only on a
# 2xx, so a caller can never report a receipt Discord did not record.
fm_phone_react() (
  local message_id=$1 body='' code rc
  fm_phone_discord_id_valid "$message_id" || return 1
  trap 'rm -f "$body"' EXIT HUP INT TERM
  body=$(mktemp "${TMPDIR:-/tmp}/fm-phone-react.XXXXXX") || return 1
  code=$(fm_phone_api_request PUT react "$message_id" "$body")
  rc=$?
  [ "$rc" = 0 ] || return 1
  case "$code" in
    2[0-9][0-9]) return 0 ;;
    *) return 1 ;;
  esac
)

# Edit one existing message in place. Prints the HTTP code so the caller can
# tell "someone else's or deleted message" (403/404) apart from a real failure,
# and returns 1 only when the request could not be made at all.
fm_phone_edit_message() (
  local message_id=$1 payload=$2 body='' code rc
  fm_phone_discord_id_valid "$message_id" || return 1
  trap 'rm -f "$body"' EXIT HUP INT TERM
  body=$(mktemp "${TMPDIR:-/tmp}/fm-phone-edit.XXXXXX") || return 1
  code=$(fm_phone_api_request PATCH message "$message_id" "$body" "$payload")
  rc=$?
  [ "$rc" = 0 ] || return 1
  printf '%s' "$code"
)

# Pin one message. Prints the HTTP code; 403 means the bot has no Manage
# Messages permission in that channel, which callers must degrade around rather
# than treat as a delivery failure.
fm_phone_pin_message() (
  local message_id=$1 body='' code rc
  fm_phone_discord_id_valid "$message_id" || return 1
  trap 'rm -f "$body"' EXIT HUP INT TERM
  body=$(mktemp "${TMPDIR:-/tmp}/fm-phone-pin.XXXXXX") || return 1
  code=$(fm_phone_api_request PUT pin "$message_id" "$body")
  rc=$?
  [ "$rc" = 0 ] || return 1
  printf '%s' "$code"
)

# Build a Discord message payload. REPLY_ID may be empty; when present it is a
# safe numeric snowflake and only the first chunk should carry the reference.
fm_phone_message_payload() {
  local text=$1 reply_id=${2:-}
  [ -z "$reply_id" ] || fm_phone_discord_id_valid "$reply_id" || return 1
  jq -cn \
    --arg text "$text" \
    --arg reply "$reply_id" \
    --arg channel "$FM_PHONE_CHANNEL" '
      {content:$text, allowed_mentions:{parse:[], replied_user:false}}
      + (if $reply == "" then {}
         else {message_reference:{message_id:$reply, channel_id:$channel, fail_if_not_exists:false}}
         end)
    '
}

# Build the live-summary payload. It is a plain content message with every
# mention suppressed: the summary is a standing reference the captain reads when
# they choose to, never an interruption.
fm_phone_summary_payload() {
  jq -cn --arg text "$1" '{content: $text, allowed_mentions: {parse: []}}'
}

# Read one durable Discord id this home recorded for itself. Both such records
# share this reader so their guarantees cannot drift: the artifact has to be a
# private mode-600 regular file holding exactly one line, and that line has to
# be a plausible snowflake. Returns 2 when the file is not there at all, so a
# caller can tell "never recorded" apart from "recorded but unusable".
fm_phone_id_file_read() {
  local state=$1 name=$2 file="$1/$2" value _extra
  if [ ! -e "$file" ] && [ ! -L "$file" ]; then
    return 2
  fi
  fmx_private_artifact_file_valid "$state" "$name" 600 || return 1
  exec 8< "$file" || return 1
  IFS= read -r value <&8 || { exec 8<&-; return 1; }
  if IFS= read -r _extra <&8; then
    exec 8<&-
    return 1
  fi
  exec 8<&-
  fm_phone_discord_id_valid "$value" || return 1
  printf '%s\n' "$value"
}

# The durable identity of this home's live summary message. Keeping the id on
# disk is what makes the summary editable across a restart instead of being
# reposted; losing it is recoverable from channel history, but reposting is not
# recoverable at all, so this write is checked by every caller.
fm_phone_summary_id_get() {
  fm_phone_id_file_read "$1" phone-summary-id || return 1
}

fm_phone_summary_id_set() {
  local state=$1 message_id=$2
  fm_phone_discord_id_valid "$message_id" || return 1
  printf '%s\n' "$message_id" \
    | fmx_private_artifact_publish_stdin "$state" phone-summary-id 600
}

# A never-recorded cursor reads as 0, which is what makes the first sweep a
# baseline instead of a replay of the channel's whole history.
fm_phone_cursor_get() {
  local value rc
  value=$(fm_phone_id_file_read "$1" phone-cursor)
  rc=$?
  case "$rc" in
    0) printf '%s\n' "$value" ;;
    2) printf '0\n' ;;
    *) return 1 ;;
  esac
}

fm_phone_cursor_set() {
  local state=$1 cursor=$2
  fm_phone_discord_id_valid "$cursor" || return 1
  printf '%s\n' "$cursor" \
    | fmx_private_artifact_publish_stdin "$state" phone-cursor 600
}

# Print a Discord snowflake for the current local time using Discord's public
# 2015-01-01 epoch and 22-bit shift. It is the last-resort baseline for a
# missing cursor on a channel that has no message id to anchor to, never an
# identifier for a real message, and never preferred over an id Discord itself
# returned. Fails when the clock or the shell's integer width cannot produce a
# plausible snowflake.
fm_phone_now_snowflake() {
  local secs value
  secs=$(date +%s 2>/dev/null) || return 1
  case "$secs" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "$secs" -gt 1420070400 ] || return 1
  value=$(( (secs * 1000 - 1420070400000) * 4194304 )) || return 1
  fm_phone_discord_id_valid "$value" || return 1
  [ "${#value}" -ge 17 ] && [ "${#value}" -le 19 ] || return 1
  printf '%s' "$value"
}

# Return 0 when A is strictly newer than B, comparing arbitrary-length decimal
# Discord snowflakes without numeric conversion or floating-point precision.
fm_phone_id_newer() {
  local a=$1 b=$2
  fm_phone_discord_id_valid "$a" || return 1
  fm_phone_discord_id_valid "$b" || return 1
  [ "${#a}" -gt "${#b}" ] && return 0
  [ "${#a}" -lt "${#b}" ] && return 1
  [[ "$a" > "$b" ]]
}

# Atomically stash one normalized Discord message object. Return 0 for a newly
# published inbox entry, 1 when the same valid id already exists, and 2 on an
# unsafe path or write failure.
fm_phone_inbox_stash() (
  local state=$1 message_id=$2 json_file=$3
  fm_phone_discord_id_valid "$message_id" || return 2
  set -o pipefail
  jq -c '.' "$json_file" 2>/dev/null \
    | fmx_private_artifact_publish_stdin_once "$state/phone-inbox" "$message_id.json" 600
)
